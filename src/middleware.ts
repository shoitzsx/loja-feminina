import { NextResponse, type NextRequest } from "next/server";

// Modo "somente relatório": o navegador avisa no console o que violaria, sem bloquear nada.
// Depois de validar em produção (Etapa 8 do plano), trocar para Content-Security-Policy.
const CSP_REPORT_ONLY = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-src https://challenges.cloudflare.com",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'"
].join("; ");

export function middleware(request: NextRequest) {
  const response = NextResponse.next();

  response.headers.set("X-Frame-Options", "DENY");
  response.headers.set("X-Content-Type-Options", "nosniff");
  response.headers.set("Referrer-Policy", "strict-origin-when-cross-origin");
  response.headers.set("Permissions-Policy", "camera=(), microphone=(), geolocation=()");
  response.headers.set("X-DNS-Prefetch-Control", "on");

  response.headers.set("Content-Security-Policy-Report-Only", CSP_REPORT_ONLY);

  // Em produção o site só existe em HTTPS; em desenvolvimento (http://localhost) não se envia HSTS.
  const isHttps = request.headers.get("x-forwarded-proto") === "https";
  if (isHttps || process.env.NODE_ENV === "production") {
    response.headers.set("Strict-Transport-Security", "max-age=31536000; includeSubDomains; preload");
  }

  return response;
}

export const config = {
  matcher: ["/((?!_next/static|_next/image|favicon.ico).*)"]
};
